import CoreGraphics

/// Состояние карты деревни, которое должно пережить уход с вкладки
/// «Деревня» и возврат обратно. Хранится в `MainTabView` как `@State`
/// (по ссылке — класс), прокидывается в `VillageMapView` и дальше в
/// `ZoomableMapContainer`.
///
/// Класс намеренно НЕ `ObservableObject` — изменения зума/панорамы не должны
/// перерисовывать SwiftUI-дерево (иначе каждый свайп по карте запускал бы
/// render pass и создавал новый `ZoomableMapContainer`). Достаточно, что это
/// ссылочный тип: `UIScrollView`-координатор пишет сюда значения через
/// delegate-колбэки, а при следующем показе экрана — читает.
@MainActor
final class VillageMapViewState {
    /// Стартовый зум = 4.0 (см. требование «при запуске приложения карта
    /// должна быть увеличена в х4»). Максимум тоже 4.0 — уменьшить можно
    /// до 1.3.
    var zoomScale: CGFloat = 4.0

    /// Текущее смещение контента. Первый раз вычисляется из
    /// `initialCenterFraction` (центрирование на главном здании), потом
    /// обновляется при каждом скролле/зуме.
    var contentOffset: CGPoint = .zero

    /// true после первой успешной инициализации scrollView — тогда при
    /// следующем показе мы восстанавливаем `contentOffset`/`zoomScale`
    /// как есть, а не центрируем карту заново.
    var hasBeenInitialized: Bool = false
}